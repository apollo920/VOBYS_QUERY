    JOIN SW_PUBLICO.FOLHA_RUBRICA R2 ON R2.ID_RUBRICA = FR2.ID_RUBRICA AND R2.COD_RUBRICA = 620205
    JOIN SW_PUBLICO.PESSOA_HISTORICO_NOMES HN ON HN.ID_PESSOA = FC.ID_PESSOA AND HN.DATA_FIM IS NULL
