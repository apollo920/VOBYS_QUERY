    FR.VALOR_CALCULADO VALOR_RUBRICA_119100,
    R2.NOME_RUBRICA RUBRICA,
    FR2.VALOR_CALCULADO VALOR_RUBRICA_620205
FROM
    SW_ADAPI.FOLHA_CONTRACHEQUE FC
    JOIN SW_ADAPI.FOLHA FO ON FO.ID_FOLHA = FC.ID_FOLHA
    JOIN SW_ADAPI.FOLHA_FUNC_RUBRICA FR ON FR.ID_FOLHA_FUNCIONARIO = FC.ID_FOLHA_FUNCIONARIO
    JOIN SW_ADAPI.FOLHA_FUNC_RUBRICA FR2 ON FR2.ID_FOLHA_FUNCIONARIO = FC.ID_FOLHA_FUNCIONARIO
