SELECT 
    'CBMPI' ORGAO,
    FO.CHAVE_FOLHA,
    FO.DESCRICAO DESCRICAO_FOLHA,
    CR.ID_REFERENCIA,
    CR.NOME_REFERENCIA REFERENCIA,
    CC.NOME_CLASSE CLASSE,
    CP.NOME_PADRAO PADRAO,
    CN.NOME_NIVEL NIVEL,
    NR.ID_NIVEL_REFERENCIA_FOLHA,
    NR.VALOR_REFERENCIA
FROM
    SW_CBMPI.FOLHA FO
    JOIN SW_CBMPI.FOLHA_VALOR_NIVEL_REFERENCIA NR ON NR.ID_FOLHA = FO.ID_FOLHA
    JOIN SW_CBMPI.RHB_CARREIRA_REFERENCIA CR ON CR.ID_REFERENCIA = NR.ID_REFERENCIA
    LEFT JOIN SW_CBMPI.RHB_CARREIRA_PADRAO CP ON CP.ID_PADRAO = CR.ID_PADRAO
    LEFT JOIN SW_CBMPI.RHB_CARREIRA_CLASSE CC ON CC.ID_CLASSE = CR.ID_CLASSE
    LEFT JOIN SW_CBMPI.RHB_CARREIRA_NIVEL CN ON CN.ID_NIVEL = CR.ID_NIVEL
WHERE 
    FO.ID_TIPO_FOLHA = 1000000
    AND FO.MES = 4
    AND FO.ANO = 2026
    AND FO.CHAVE_FOLHA = '04/2026-100';
    
