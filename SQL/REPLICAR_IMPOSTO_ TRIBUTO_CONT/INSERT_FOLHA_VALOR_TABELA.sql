SELECT
    'AGESPISA02' AS ORGAO,
    FO2.CHAVE_FOLHA,
    VT.ID_TABELA,
    VT.FAIXA,
    VT2.VALOR_INICIAL AS VALOR_INICIAL_DESTINO,
    VT2.VALOR_FINAL   AS VALOR_FINAL_DESTINO,
    VT2.PERCENTUAL    AS PERCENTUAL_DESTINO,
    VT2.VALOR_1       AS VALOR_1_DESTINO,
    VT2.VALOR_2       AS VALOR_2_DESTINO,
    VT.VALOR_INICIAL  AS VALOR_INICIAL_ORIGEM,
    VT.VALOR_FINAL    AS VALOR_FINAL_ORIGEM,
    VT.PERCENTUAL     AS PERCENTUAL_ORIGEM,
    VT.VALOR_1        AS VALOR_1_ORIGEM,
    VT.VALOR_2        AS VALOR_2_ORIGEM,
    CASE
        WHEN VT2.ID_VALOR_TABELA IS NOT NULL THEN
            'UPDATE SW_AGESPISA02.FOLHA_VALOR_TABELA SET '
            || 'VALOR_INICIAL = ' || NVL(REPLACE(TO_CHAR(VT.VALOR_INICIAL), ',', '.'), 'NULL')
            || ', VALOR_FINAL = ' || NVL(REPLACE(TO_CHAR(VT.VALOR_FINAL), ',', '.'), 'NULL')
            || ', PERCENTUAL = '  || NVL(REPLACE(TO_CHAR(VT.PERCENTUAL), ',', '.'), 'NULL')
            || ', VALOR_1 = '     || NVL(REPLACE(TO_CHAR(VT.VALOR_1), ',', '.'), 'NULL')
            || ', VALOR_2 = '     || NVL(REPLACE(TO_CHAR(VT.VALOR_2), ',', '.'), 'NULL')
            || ', VALOR_3 = '     || NVL(REPLACE(TO_CHAR(VT.VALOR_3), ',', '.'), 'NULL')
            || ', DATA_1 = '      || NVL2(VT.DATA_1, 'TO_DATE(''' || TO_CHAR(VT.DATA_1, 'DD/MM/YYYY HH24:MI:SS') || ''', ''DD/MM/YYYY HH24:MI:SS'')', 'NULL')
            || ', DATA_2 = '      || NVL2(VT.DATA_2, 'TO_DATE(''' || TO_CHAR(VT.DATA_2, 'DD/MM/YYYY HH24:MI:SS') || ''', ''DD/MM/YYYY HH24:MI:SS'')', 'NULL')
            || ' WHERE ID_VALOR_TABELA = ' || VT2.ID_VALOR_TABELA || ';'
        ELSE
            'INSERT INTO SW_AGESPISA02.FOLHA_VALOR_TABELA (ID_VALOR_TABELA, ID_FOLHA, ID_TABELA, FAIXA, VALOR_INICIAL, VALOR_FINAL, PERCENTUAL, VALOR_1, VALOR_2, VALOR_3, DATA_1, DATA_2) VALUES (SW_AGESPISA02.SQ_PK_VALOR_FOLHA_TABELA.NEXTVAL, '
            || FO2.ID_FOLHA || ', '
            || VT.ID_TABELA || ', '
            || NVL(TO_CHAR(VT.FAIXA), 'NULL') || ', '
            || NVL(REPLACE(TO_CHAR(VT.VALOR_INICIAL), ',', '.'), 'NULL') || ', '
            || NVL(REPLACE(TO_CHAR(VT.VALOR_FINAL), ',', '.'), 'NULL') || ', '
            || NVL(REPLACE(TO_CHAR(VT.PERCENTUAL), ',', '.'), 'NULL') || ', '
            || NVL(REPLACE(TO_CHAR(VT.VALOR_1), ',', '.'), 'NULL') || ', '
            || NVL(REPLACE(TO_CHAR(VT.VALOR_2), ',', '.'), 'NULL') || ', '
            || NVL(REPLACE(TO_CHAR(VT.VALOR_3), ',', '.'), 'NULL') || ', '
            || NVL2(VT.DATA_1, 'TO_DATE(''' || TO_CHAR(VT.DATA_1, 'DD/MM/YYYY HH24:MI:SS') || ''', ''DD/MM/YYYY HH24:MI:SS'')', 'NULL') || ', '
            || NVL2(VT.DATA_2, 'TO_DATE(''' || TO_CHAR(VT.DATA_2, 'DD/MM/YYYY HH24:MI:SS') || ''', ''DD/MM/YYYY HH24:MI:SS'')', 'NULL') || ');'
    END AS SCRIPT_
FROM
    SW_AGESPISA.FOLHA FO
    JOIN SW_AGESPISA.FOLHA_VALOR_TABELA VT ON VT.ID_FOLHA = FO.ID_FOLHA
    JOIN SW_AGESPISA02.FOLHA FO2
        ON FO2.MES = 10
       AND FO2.ANO = 2026
       AND FO2.CHAVE_FOLHA = '10/2026-300'
    LEFT JOIN SW_AGESPISA02.FOLHA_VALOR_TABELA VT2
        ON VT2.ID_FOLHA = FO2.ID_FOLHA
       AND VT2.ID_TABELA = VT.ID_TABELA
       AND NVL(VT2.FAIXA, -1) = NVL(VT.FAIXA, -1)
WHERE
    FO.MES = 10
    AND FO.ANO = 2026
    AND FO.CHAVE_FOLHA = '10/2026-100'
ORDER BY
    VT.ID_TABELA,
    VT.FAIXA;