		X.CODIGO_SEFAZ,
		X.ID_FUNCIONARIO,
		X.ID_FOLHA_FUNCIONARIO,
		X.MATRICULA,
		X.CPF,
		X.COD_GRUPO,
		X.DESCRICAO_GRUPO,
		X.TIPO_RELATORIO,
		CASE
            WHEN X.COD_RUBRICA IN (714100, 714110) THEN 'BASE'
            WHEN X.COD_RUBRICA_LEGADO IN ('901') THEN 'FUNDO'
            WHEN X.COD_RUBRICA IN (714400, 714405, 714410, 714420, 714430, 714403) THEN 'PATRONAL'
            WHEN X.COD_RUBRICA IN (999997) THEN 'BRUTO'
        END AS TIPO_RUBRICA,
		X.VALOR_CALCULADO
	FROM
		(
            SELECT
				FF.ID_FOLHA_FUNCIONARIO,
				F.ID_FUNCIONARIO,
				REGEXP_REPLACE(NVL(FF.MATR_DEPENDENTE, PV.COD_INSTITUCIONAL), '[^0-9A-Za-z]', '')    AS MATRICULA,
				PDC.CPF_PESSOA                                              AS CPF,
				E.ORGAO_SIAFI                                               AS ORGAO,
				CS.CODIGO_SEFAZ,
				FR.COD_RUBRICA,
				FR.COD_RUBRICA_LEGADO,
				FFR.VALOR_CALCULADO,
				FO.MES,
				FO.ANO,
				FO.ID_TIPO_FOLHA,
				NVL(GRUP_REL.CODIGO, 'SEM GRUPO')                           AS COD_GRUPO,
				NVL(GRUP_REL.DESCRICAO, 'SEM GRUPO')                        AS DESCRICAO_GRUPO,
				GRUP_REL.TIPO_RELATORIO                                     AS TIPO_RELATORIO
			FROM
				SW_PUBLICO.PESSOA P
				JOIN SW_PUBLICO.PESSOA_DOC_CPF PDC ON PDC.ID_PESSOA = P.ID_PESSOA AND PDC.DATA_BAIXA IS NULL
				JOIN SW_PUBLICO.EMPRESA E ON E.SIGLA = 'FUNPREV'
				JOIN SW_FUNPREV.PESSOA_VINCULO PV ON PV.ID_PESSOA = P.ID_PESSOA
				JOIN SW_FUNPREV.FUNCIONARIO F ON F.ID_PESSOA_VINCULO = PV.ID_PESSOA_VINCULO
				JOIN SW_FUNPREV.FOLHA_FUNC FF ON FF.ID_FUNCIONARIO = F.ID_FUNCIONARIO
				LEFT JOIN SW_FUNPREV.RHB_LOTACAO LOT ON LOT.COD_LOTACAO = FF.COD_LOTACAO
				LEFT JOIN SW_FUNPREV.RHB_LOTACAO_GRUPO LOT_GRUP ON LOT_GRUP.ID_LOTACAO = LOT.ID_LOTACAO
				LEFT JOIN SW_FUNPREV.RHB_LOTA_GRUPO_RELATORIO GRUP_REL ON GRUP_REL.ID_LOTA_GRUPO_RELATORIO = COALESCE(LOT_GRUP.ID_LOTA_GRUPO_RELATORIO,(
					SELECT
						X.ID_LOTA_GRUPO_RELATORIO
					FROM
						SW_FUNPREV.RHB_LOTA_GRUPO_RELATORIO X
					WHERE
						X.CODIGO = E.ORGAO_SIAFI
				))
				JOIN SW_FUNPREV.FOLHA FO ON FO.ID_FOLHA = FF.ID_FOLHA
				JOIN SW_FUNPREV.FOLHA_FUNC_RUBRICA FFR ON FFR.ID_FOLHA_FUNCIONARIO = FF.ID_FOLHA_FUNCIONARIO
				JOIN SW_PUBLICO.FOLHA_RUBRICA FR ON FR.ID_RUBRICA = FFR.ID_RUBRICA
                LEFT JOIN SW_FUNPREV.FOLHA_CODIGO_SEFAZ CS ON CS.ID_CODIGO_SEFAZ = FO.ID_CODIGO_SEFAZ
			WHERE
				FO.ID_TIPO_FOLHA = 1000000
				AND FO.MES = 7
				AND FO.ANO = 2026
				AND ( FR.COD_RUBRICA IN (714100, 714110)
					OR FR.COD_RUBRICA_LEGADO IN ( '901' )
					OR FR.COD_RUBRICA IN (714400, 714405, 714410, 714420, 714430, 714403)
					OR FR.COD_RUBRICA IN (999997) )
                AND NOT EXISTS (
                    SELECT
                        1
                    FROM
                        SW_FUNPREV.FOLHA_FICHA_FINANCEIRA
                    WHERE  
                        ID_RUBRICA IN (1000347, 1555749)
                        AND ID_FOLHA_FUNCIONARIO = FF.ID_FOLHA_FUNCIONARIO
                )
        ) X
)
