            JOIN SW_FUNPREV.FUNCIONARIO_INGRESSO FI ON FI.ID_FUNCIONARIO = NVL(FC.ID_FUNCIONARIO, PC.ID_FUNCIONARIO)
        WHERE
            FO.ID_TIPO_FOLHA = 1000000
