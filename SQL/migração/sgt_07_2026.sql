        JOIN SW_SEDUC.FUNCIONARIO F                  ON F.ID_PESSOA_VINCULO = PV.ID_PESSOA_VINCULO
        JOIN SW_SEDUC.FUNCIONARIO_INF_GOVERNO FIG    ON FIG.ID_FUNCIONARIO = F.ID_FUNCIONARIO

    UNION ALL

    -- 12) FUNCIONARIO_INF_PARAMETRIZADA
    SELECT 12, 'FUNCIONARIO_INF_PARAMETRIZADA', A.MATRICULA, FIP.ID_INFORMACAO_PARAMETRIZADA,
        FIP.DATA_CADASTRO,
        'UPDATE SW_SEDUC.FUNCIONARIO_INF_PARAMETRIZADA SET DATA_CADASTRO = TO_DATE(''03/07/2026'',''DD/MM/YYYY'') WHERE ID_INFORMACAO_PARAMETRIZADA = '
            || FIP.ID_INFORMACAO_PARAMETRIZADA || ';'
    FROM ABASE A
        JOIN SW_SEDUC.PESSOA_VINCULO PV                    ON PV.COD_INSTITUCIONAL = A.MATRICULA
        JOIN SW_SEDUC.FUNCIONARIO F                        ON F.ID_PESSOA_VINCULO = PV.ID_PESSOA_VINCULO
        JOIN SW_SEDUC.FUNCIONARIO_INF_PARAMETRIZADA FIP    ON FIP.ID_FUNCIONARIO = F.ID_FUNCIONARIO
)
ORDER BY ORDEM, MATRICULA;