    FC.DATA_NASCIMENTO,
    TRUNC(MONTHS_BETWEEN(SYSDATE, TO_DATE(FC.DATA_NASCIMENTO)) / 12) IDADE,
    SX.NOME_SEXO SEXO,
    M.NOME_MUNICIPIO MUNICIPIO,
    CT.CODIGO COD_CATEGORIA_TRABALHADOR,
    CT.DESCRICAO CATEGORIA_TRABALHADOR,
    NULL DIVISAO,
    CASE ES.IND_SITUACAO
        WHEN 'A' THEN 'Ativo'
        WHEN 'S' THEN 'Suspensão Temporária'
        WHEN 'V' THEN 'Voluntário'
    END SITUACAO,
    FC.REGIME,
    NULL TIPO_FUNCIONARIO,
    NULL REGIME_PREVIDENCIARIO,
    FS.DESCRICAO_FONTE,
    FO.MASCARA CHAVE_FOLHA,
    FO.MES,
    FO.ANO,
    R.COD_RUBRICA,
    R.NOME_RUBRICA,
    R.TIPO,
    FF.VALOR VALOR,
    P.NOME_MAE,
    TT.DESCRICAO_TIPO TIPO_FOLHA,
    FC.NOME_EMPRESA_ORIGEM ORGAO_ORIGEM
FROM
    SW_ADAPI.ESTAG_FOLHA FO
    JOIN SW_ADAPI.FOLHA_CONTRACHEQUE FC ON FC.ID_ESTAG_FOLHA = FO.ID_FOLHA
    JOIN SW_ADAPI.ESTAGIARIO E ON E.ID_ESTAGIARIO = FC.ID_ESTAGIARIO
    JOIN SW_ADAPI.ESTAGIARIO_PAGAMENTO EP ON EP.ID_FOLHA_ESTAGIARIO = FC.ID_ESTAGIARIO_PAGAMENTO
    JOIN SW_PUBLICO.PESSOA P ON P.ID_PESSOA = FC.ID_PESSOA
    LEFT JOIN SW_PUBLICO.PESSOA_ESCOLARIDADE PE ON PE.ID_PESSOA = P.ID_PESSOA AND PE.DATA_FIM IS NULL
    LEFT JOIN SW_PUBLICO.RHB_INSTRUCAO_ESCOLARIDADE IE ON IE.ID_ESCOLARIDADE = PE.ID_ESCOLARIDADE
    LEFT JOIN SW_PUBLICO.RHB_CARACT_FISICA_SEXO SX ON SX.ID_SEXO = P.ID_SEXO
    LEFT JOIN SW_PUBLICO.RHB_CEP_MUNICIPIO_IBGE M ON M.ID_MUNICIPIO = FC.ID_MUNICIPIO
    LEFT JOIN SW_ADAPI.ESTAGIARIO_SITUACAO ES ON ES.ID_ESTAGIARIO = E.ID_ESTAGIARIO --AND ES.DATA_FIM IS NULL
    LEFT JOIN SW_PUBLICO.ESB_CATEGORIA_TRABALHADOR CT ON CT.ID_ESB_CATEG_TRABALHADOR = E.ID_ESB_CATEG_TRABALHADOR
    LEFT JOIN SW_ADAPI.FOLHA_FONTE_SEFAZ FS ON FS.ID_FONTE = FO.ID_FONTE
    JOIN SW_ADAPI.ESTAG_PAGAMENTO_RUBRICA_FICHAF FF ON FF.ID_FOLHA_ESTAGIARIO = EP.ID_FOLHA_ESTAGIARIO
    JOIN SW_PUBLICO.FOLHA_RUBRICA R ON R.ID_RUBRICA = FF.ID_RUBRICA
    JOIN SW_PUBLICO.FOLHA_TAB_TIPO TT ON TT.ID_TIPO_FOLHA = FO.ID_TIPO_FOLHA
WHERE
    FC.MES = 3
    AND FC.ANO = 2026
    AND FO.ID_TIPO_FOLHA = 1000000
    AND (R.TIPO IN ('R', 'D') OR R.COD_RUBRICA = 999997)
UNION ALL
