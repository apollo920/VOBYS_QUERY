SELECT
    'AGESPISA02' AS ORGAO,
    FO.CHAVE_FOLHA,
    RF_D.ID_RUBRICA,
    RF_D.ID_FORMULA,
    'INSERT INTO SW_AGESPISA02.FOLHA_RUBRICA_INCIDENCIA (ID_INCIDENCIA_RUBRICA, ID_RUBRICA_FORMULA, DATA_CADASTRO, ID_INCIDENCIA, OBSERVACAO) VALUES (SW_AGESPISA02.SQ_PK_INCIDENCIA.NEXTVAL, '
    || RF_D.ID_RUBRICA_FORMULA || ', SYSDATE, '
    || NVL(TO_CHAR(RI.ID_INCIDENCIA), 'NULL') || ', '
    || CASE
           WHEN RI.OBSERVACAO IS NULL THEN 'NULL'
           ELSE '''' || REPLACE(RI.OBSERVACAO, '''', '''''') || ''''
       END || ');' AS INSERT_
FROM
    SW_AGESPISA02.FOLHA FO
    JOIN (
        SELECT DISTINCT
            RF_O.ID_RUBRICA,
            RF_O.ID_FORMULA,
            RI_O.ID_INCIDENCIA,
            RI_O.OBSERVACAO
        FROM
            SW_AGESPISA.FOLHA_RUBRICA_INCIDENCIA RI_O
            JOIN SW_AGESPISA.FOLHA_RUBRICA_FORMULA RF_O ON RF_O.ID_RUBRICA_FORMULA = RI_O.ID_RUBRICA_FORMULA
            JOIN SW_AGESPISA.FOLHA FO_O ON FO_O.ID_FOLHA = RF_O.ID_FOLHA
        WHERE
            FO_O.MES = 10
            AND FO_O.ANO = 2026
            AND FO_O.CHAVE_FOLHA = '10/2026-100'
    ) RI ON 1 = 1
    JOIN SW_AGESPISA02.FOLHA_RUBRICA_FORMULA RF_D
        ON RF_D.ID_FOLHA = FO.ID_FOLHA
       AND RF_D.ID_RUBRICA = RI.ID_RUBRICA
       AND NVL(RF_D.ID_FORMULA, -1) = NVL(RI.ID_FORMULA, -1)
WHERE
    FO.MES = 10
    AND FO.ANO = 2026
    AND FO.CHAVE_FOLHA = '10/2026-300'
    AND NOT EXISTS (
        SELECT
            1
        FROM
            SW_AGESPISA02.FOLHA_RUBRICA_INCIDENCIA RI2
        WHERE
            RI2.ID_RUBRICA_FORMULA = RF_D.ID_RUBRICA_FORMULA
            AND RI2.ID_INCIDENCIA = RI.ID_INCIDENCIA
    );