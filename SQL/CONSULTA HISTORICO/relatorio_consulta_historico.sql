SELECT
    'FUNPREV' ORGAO,
    HN.NOME,
    PC.CPF_PESSOA,
    AT.NOME_ENTIDADE,
    CASE
        WHEN AA.IND_ATUALIZACAO = 'I' THEN 'Inclusao'
        WHEN AA.IND_ATUALIZACAO = 'A' THEN 'Alteracao'
        WHEN AA.IND_ATUALIZACAO = 'E' THEN 'Exclusao'
        ELSE AA.IND_ATUALIZACAO
    END MODIFICAO,
    OA.MIGALHA ACAO,
    'https://siape.sead.pi.gov.br/adm/funprev/gerencial/gerencial/auditoria/auditoria/registro-auditado/' || AT.ID_TABELA LINK,
    AA.USUARIO
FROM
    SW_FUNPREV.AUDIT_TABELA AT
    JOIN SW_FUNPREV.AUDIT_ACAO AA ON AA.ID_ACAO = AT.ID_ACAO
    JOIN SW_PUBLICO.PESSOA_CERTIDAO_OBITO O ON O.ID_CERTIDAO_OBITO = AT.PK
    JOIN SW_PUBLICO.PESSOA_HISTORICO_NOMES HN ON HN.ID_PESSOA = O.ID_PESSOA AND HN.DATA_FIM IS NULL
    JOIN SW_PUBLICO.PESSOA_DOC_CPF PC ON PC.ID_PESSOA = O.ID_PESSOA AND PC.DATA_BAIXA IS NULL
    LEFT JOIN SW_PUBLICO.OBJETO_AUTORIZACAO OA ON OA.OID = AA.OID
WHERE
    AT.NOME_ENTIDADE = 'PessoaCertidaoObito'
    --AND PC.CPF_PESSOA = '239.276.743-20'