SELECT
    ORGAO,
    MATR_DEPENDENTE         AS MATRICULA,
    NOME,
    NOME_ESPECIALIDADE      AS ESPECIALIDADE,
    NOME_RUBRICA            AS RUBRICA,
    VALOR_ATUAL,
    VALOR_NOVO,
    PERCENTUAL,
    VALOR_NOVO * PERCENTUAL AS VALOR_RATEADO,
    CASE
        WHEN VALOR_NOVO > 0 THEN
            'UPDATE SW_'
            || ORGAO
            || '.FOLHA_FUNC_RUBRICA_IMPORTADA SET VALOR_MULTIPLICADOR = '
            || REPLACE(VALOR_NOVO * PERCENTUAL, ',', '.')
            || ' WHERE ID_RUBRICA_IMPORTADA = '
            || ID_RUBRICA_IMPORTADA
            || ';'
        WHEN VALOR_NOVO = 0 THEN
            'DELETE SW_'
            || ORGAO
            || '.FOLHA_FUNC_RUBRICA_IMPORTADA WHERE ID_RUBRICA_IMPORTADA = '
            || ID_RUBRICA_IMPORTADA
            || ';'
    END AS QUERY
FROM
    (
        SELECT
            'FUNPREV' AS ORGAO,
            FF.MATR_DEPENDENTE,
            HN.NOME,
            E.NOME_ESPECIALIDADE,
            CF.NOME_CATE_FUNC,
            R.NOME_RUBRICA,
            RI.VALOR_MULTIPLICADOR  AS VALOR_ATUAL,
            CASE
                WHEN E.COD_ESPECIALIDADE = '10424' THEN -- AUD.FISCAL DA FAZ. ESTADUAL
                    8400
                WHEN E.COD_ESPECIALIDADE = '10425' THEN -- AUD.FISCAL.AUX.FAZ.ESTADUAL
                    2880
                WHEN E.COD_ESPECIALIDADE = '10426' THEN -- AGENTE DE TRIBUTOS DA FAZENDA ESTADUAL
                    1620
                WHEN E.COD_ESPECIALIDADE = '10427' THEN -- ANALISTA DO TESOURO ESTADUAL
                    800
                WHEN E.COD_ESPECIALIDADE = '10428' THEN -- ANAL.AUX. DO TESOURO ESTADUAL
                    720
            END                     AS VALOR_NOVO,
            RI.ID_RUBRICA_IMPORTADA,
            CASE
                WHEN PC.PERCENTUAL = 0 THEN
                    1 / (
                        SELECT
                            COUNT(1)
                        FROM
                            SW_FUNPREV.FUNC_PENSAO_CIVIL X
                        WHERE
                            X.ID_FUNCIONARIO = F.ID_FUNCIONARIO
                    )
                ELSE
                    PC.PERCENTUAL / 100
            END                     AS PERCENTUAL
        FROM
                 SW_FUNPREV.PESSOA_VINCULO PV
            JOIN SW_FUNPREV.FUNCIONARIO F ON F.ID_PESSOA_VINCULO = PV.ID_PESSOA_VINCULO
            JOIN SW_FUNPREV.FOLHA_FUNC FF ON FF.ID_FUNCIONARIO = F.ID_FUNCIONARIO
            JOIN SW_PUBLICO.PESSOA_HISTORICO_NOMES HN ON HN.ID_PESSOA = FF.ID_PESSOA_DEPENDENTE AND HN.DATA_FIM IS NULL
            JOIN SW_FUNPREV.FOLHA_FUNC_RUBRICA_IMPORTADA RI ON RI.ID_FOLHA_FUNCIONARIO = FF.ID_FOLHA_FUNCIONARIO
            JOIN SW_FUNPREV.FOLHA FO ON FO.ID_FOLHA = FF.ID_FOLHA
            JOIN SW_PUBLICO.FOLHA_RUBRICA R ON R.ID_RUBRICA = RI.ID_RUBRICA
            JOIN SW_FUNPREV.FUNCIONARIO_INGRESSO FI ON FI.ID_FUNCIONARIO = F.ID_FUNCIONARIO
            JOIN SW_FUNPREV.RHB_CARREIRA_CATEG_ESPECIALID E ON E.ID_ESPECIALIDADE = FI.ID_ESPECIALIDADE
            JOIN SW_PUBLICO.PREV_PROP_ORGAO_ORIGEM PP ON ( PP.ID_FUNCIONARIO_PAGAMENTO = F.ID_FUNCIONARIO AND PP.ID_EMPRESA_PAGAMENTO = 63 )
            JOIN SW_PUBLICO.PREV_PROP_PLAN_CATE_FUNCIONAL PCF ON PCF.ID_PLAN_CATE_FUNCIONAL = PP.ID_PLAN_CATE_FUNC
            JOIN SW_PUBLICO.PREV_PROP_CATE_FUNCIONAL CF ON CF.ID_CATE_FUNC = PCF.ID_CATE_FUNC
            JOIN SW_FUNPREV.FUNC_PENSAO_CIVIL PC ON PC.ID_PENSIONISTA = FF.ID_PENSIONISTA
        WHERE
                FO.MES = 7
            AND FO.ANO = 2026
            AND R.COD_RUBRICA IN ( 132908, 112906, 112907, 122906, 132906, 142905, 152905 )
        ORDER BY
            FF.MATR_DEPENDENTE
    )
WHERE VALOR_ATUAL <> (VALOR_NOVO * PERCENTUAL)