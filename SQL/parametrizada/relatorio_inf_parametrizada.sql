SELECT 
    'EMPRESA' ORGAO,
    HN.NOME,
    PC.CPF_PESSOA,
    PV.COD_INSTITUCIONAL MATRICULA,
    PA.NOME_PARAMETRO CAMPO,
    IP.OBSERVACAO,
    IP.DATA_INICIO DATA_INICIO_PARAMETRIZADA,
    IP.DATA_FIM DATA_FIM_PARAMETRIZADA,
    E.NOME_FANTASIA ORGAO_CESSAO,
    E1.NOME_FANTASIA ORGAO_REQUISITANTE,
    CR.DATA_INICIO DATA_INICIO_CESSAO_REQUISICAO_INTERNA,
    CR.DATA_FIM DATA_FIM_CESSAO_REQUISICAO_INTERNA,
    CR.ID_FUNCIONARIO_REQUISICAO
FROM 
    SW_EMPRESA.PESSOA_VINCULO PV 
    JOIN SW_EMPRESA.FUNCIONARIO F ON F.ID_PESSOA_VINCULO = PV.ID_PESSOA_VINCULO
    LEFT JOIN SW_EMPRESA.FUNCIONARIO_INF_PARAMETRIZADA IP ON IP.ID_FUNCIONARIO = F.ID_FUNCIONARIO
    JOIN SW_PUBLICO.FUNC_CESSAO_REQUISICAO_I CR ON CR.ID_FUNCIONARIO_CESSAO = F.ID_FUNCIONARIO
    JOIN SW_PUBLICO.PESSOA_HISTORICO_NOMES HN ON HN.ID_PESSOA = PV.ID_PESSOA AND HN.DATA_FIM IS NULL
    JOIN SW_PUBLICO.PESSOA_DOC_CPF PC ON PC.ID_PESSOA = PV.ID_PESSOA AND PC.DATA_BAIXA IS NULL
    LEFT JOIN SW_PUBLICO.RHB_INFORMACOES_PARAMETRIZADAS PA ON PA.ID_PARAMETRO = IP.ID_PARAMETRO
    LEFT JOIN SW_PUBLICO.EMPRESA E ON E.ID_EMPRESA = CR.ID_EMPRESA_CESSAO
    LEFT JOIN SW_PUBLICO.EMPRESA E1 ON E1.ID_EMPRESA = CR.ID_EMPRESA_REQUISITANTE
UNION ALL
