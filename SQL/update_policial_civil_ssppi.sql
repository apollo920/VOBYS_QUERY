SELECT 
    'SSPPI' ORGAO,
    FO.CHAVE_FOLHA,
    FO.DESCRICAO DESCRICAO_FOLHA,
    CR.ID_REFERENCIA,
    CR.NOME_REFERENCIA REFERENCIA,
    CC.NOME_CLASSE CLASSE,
    CP.NOME_PADRAO PADRAO,
    CN.NOME_NIVEL NIVEL,
    NR.ID_NIVEL_REFERENCIA_FOLHA,
    NR.VALOR_REFERENCIA,
    NR_MAR.VALOR_REFERENCIA AS VALOR_REFERENCIA_MARCO,
    FFR.VALOR_CALCULADO,
    FFR_MAR.VALOR_CALCULADO AS VALOR_CALCULADO_MARCO
FROM
    SW_SSPPI.FOLHA FO
    
    JOIN SW_SSPPI.FOLHA_FUNC FF
    ON FF.ID_FOLHA = FO.ID_FOLHA

    JOIN SW_SSPPI.FOLHA_FUNC_RUBRICA FFR 
        ON FFR.ID_FOLHA = FO.ID_FOLHA
        
    JOIN SW_SSPPI.FOLHA_VALOR_NIVEL_REFERENCIA NR 
        ON NR.ID_FOLHA = FO.ID_FOLHA
        
    JOIN SW_SSPPI.RHB_CARREIRA_REFERENCIA CR 
        ON CR.ID_REFERENCIA = NR.ID_REFERENCIA
        
    LEFT JOIN SW_SSPPI.RHB_CARREIRA_PADRAO CP 
        ON CP.ID_PADRAO = CR.ID_PADRAO
        
    LEFT JOIN SW_SSPPI.RHB_CARREIRA_CLASSE CC 
        ON CC.ID_CLASSE = CR.ID_CLASSE
        
    LEFT JOIN SW_SSPPI.RHB_CARREIRA_NIVEL CN 
        ON CN.ID_NIVEL = CR.ID_NIVEL
        
    LEFT JOIN (
        SELECT 
            FFR.ID_FUNCIONARIO,
            FFR.ID_RUBRICA,
            FFR.VALOR_CALCULADO
        FROM SW_SSPPI.FOLHA FO
        JOIN SW_SSPPI.FOLHA_FUNC_RUBRICA FFR 
            ON FFR.ID_FOLHA = FO.ID_FOLHA
        WHERE 
            FO.ID_TIPO_FOLHA = 1000000
            AND FO.MES = 3
            AND FO.ANO = 2026
    ) FFR_MAR
        ON FFR_MAR.ID_FUNCIONARIO = FFR.ID_FUNCIONARIO
        AND FFR_MAR.ID_RUBRICA = FFR.ID_RUBRICA  
    LEFT JOIN (
        SELECT 
            NR.ID_REFERENCIA,
            NR.VALOR_REFERENCIA
        FROM SW_SSPPI.FOLHA FO
        JOIN SW_SSPPI.FOLHA_VALOR_NIVEL_REFERENCIA NR 
            ON NR.ID_FOLHA = FO.ID_FOLHA
        WHERE 
            FO.ID_TIPO_FOLHA = 1000000
            AND FO.MES = 3
            AND FO.ANO = 2026
    ) NR_MAR
        ON NR_MAR.ID_REFERENCIA = NR.ID_REFERENCIA  
WHERE 
    FO.ID_TIPO_FOLHA = 1000000
    AND FO.MES = 4
    AND FO.ANO = 2026
    AND FO.CHAVE_FOLHA = '04/2026-100';

