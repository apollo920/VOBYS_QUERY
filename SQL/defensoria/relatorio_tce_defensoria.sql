    LEFT JOIN SW_PUBLICO.RHB_CEP_MUNICIPIO_IBGE CM ON CM.ID_MUNICIPIO = L.ID_MUNICIPIO
    JOIN SW_PUBLICO.EMPRESA E ON E.SIGLA = 'DEFENSORIA'
WHERE 
    FC.MES = 7
    AND FC.ANO = 2026
    AND R.TIPO IN ('R', 'D')
    AND FC.ID_ESTAGIARIO IS NOT NULL
