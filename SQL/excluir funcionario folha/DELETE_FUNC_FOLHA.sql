SELECT 
    FO.CHAVE_FOLHA,
    FO.ID_FOLHA,
    HN.NOME,
    FF.COD_INSTITUCIONAL,
    FF.ID_PESSOA_FUNCIONARIO,
    FF.ID_FOLHA_FUNCIONARIO,
    'DELETE FROM SW_SETRE.FOLHA_FUNC_RUBRICA_IMPORTADA WHERE ID_FOLHA_FUNCIONARIO = ' || FF.ID_FOLHA_FUNCIONARIO || ';' DELETE_,
    'DELETE FROM SW_SETRE.FOLHA_IMP_FUNC_PERFIL WHERE ID_FOLHA_FUNCIONARIO = ' || FF.ID_FOLHA_FUNCIONARIO || ';' DELETE_,
    'DELETE FROM SW_SETRE.FOLHA_IMP_FUNC_PERFIL WHERE ID_FOLHA_FUNCIONARIO = ' || FF.ID_FOLHA_FUNCIONARIO || ';' DELETE_,
    'DELETE FROM SW_SETRE.FOLHA_FUNC_PERFIL WHERE ID_FOLHA_FUNCIONARIO = ' || FF.ID_FOLHA_FUNCIONARIO || ';' DELETE_,
    'DELETE FROM SW_SETRE.FOLHA_FUNC_AUDITORIA WHERE ID_FOLHA_FUNCIONARIO = ' || FF.ID_FOLHA_FUNCIONARIO || ';' DELETE_,
    'DELETE FROM SW_SETRE.FOLHA_FUNC WHERE ID_FOLHA_FUNCIONARIO = ' || FF.ID_FOLHA_FUNCIONARIO || ';' DELETE_
FROM 
    SW_SETRE.FOLHA FO
    JOIN SW_SETRE.FOLHA_FUNC FF ON FF.ID_FOLHA = FO.ID_FOLHA
    JOIN SW_PUBLICO.PESSOA_HISTORICO_NOMES HN ON HN.ID_PESSOA = FF.ID_PESSOA_FUNCIONARIO AND HN.DATA_FIM IS NULL
    JOIN SW_PUBLICO.PESSOA_DOC_CPF PC ON PC.ID_PESSOA = FF.ID_PESSOA_FUNCIONARIO AND PC.DATA_BAIXA IS NULL
WHERE 
    FO.CHAVE_FOLHA = '10/2026-29'
    